"""Stop-token supervision for Gemma 4 agent fine-tuning: a recipe audit (CPU) and a probability probe (GPU), on Modal.

audit:  renders a tool-calling trajectory with the Gemma 4 chat template and reports, for several loss-mask recipes,
        how many of the `<|tool_response>` stop positions (the token the model must predict to end a tool-call turn)
        are supervised, and how many tool-result tokens are supervised by mistake.
probe:  teacher-forces held-out trajectories through the base model and each adapter and reports, at every position
        where the next token is the `<|tool_response>` stop, the probability of stopping and of opening another
        `<|tool_call>` instead.

Usage:
  modal run analysis/stop_token_probe.py::audit --data artifacts/sft/heldout-fastapi.jsonl
  modal run analysis/stop_token_probe.py::probe --data artifacts/sft/heldout-fastapi.jsonl \
      --base-model google/gemma-4-31b-it --adapters 31b-lora-r1,31b-lora-r1-maskfix,31b-lora-r2 --gpu H200
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import modal

image = (
    modal.Image.debian_slim(python_version='3.12')
    .pip_install('torch==2.9.0', 'transformers>=4.57', 'peft>=0.17', 'accelerate>=1.10', 'datasets>=3.0', 'sentencepiece',
                 'protobuf', 'huggingface_hub>=0.34', 'trl')
    .env({'HF_HOME': '/vol/hf', 'TOKENIZERS_PARALLELISM': 'false'})
)
vol = modal.Volume.from_name('g4-training', create_if_missing=True)
app = modal.App('g4-stop-probe', image=image)
_FN = dict(volumes={'/vol': vol}, secrets=[modal.Secret.from_name('huggingface')])
STOP, CALL_OPEN, CALL_CLOSE, RESP_CLOSE, TURN_OPEN, TURN_CLOSE = '<|tool_response>', '<|tool_call>', '<tool_call|>', '<tool_response|>', '<|turn>', '<turn|>'


def _segments(tok, ids):
    """Per-token labels: 'model' (generated by the model), 'stop' (a <|tool_response> that ends a tool-call turn),
    'result' (tool-response body and its closing tag), 'other' (system, user, turn headers)."""
    t = {k: tok.convert_tokens_to_ids(k) for k in (STOP, CALL_OPEN, CALL_CLOSE, RESP_CLOSE, TURN_OPEN, TURN_CLOSE)}
    model_ids = set(tok.encode('model', add_special_tokens=False))
    seg = ['other'] * len(ids)
    in_model = in_resp = False
    i = 0
    while i < len(ids):
        x = ids[i]
        if x == t[TURN_OPEN]:
            in_model = i + 1 < len(ids) and ids[i + 1] in model_ids
            i += 3 if in_model else 2
            continue
        if in_model:
            if x == t[STOP]:
                seg[i] = 'stop'; in_resp = True
            elif in_resp:
                seg[i] = 'result'
                if x == t[RESP_CLOSE]:
                    in_resp = False
            else:
                seg[i] = 'model'
            if x == t[TURN_CLOSE]:
                in_model = False
        i += 1
    return seg


def _mask_turns_only(seg):   # the mask that produced the looping adapter: model-generated tokens, not the stop
    return [s == 'model' for s in seg]


def _mask_fixed(seg):        # the corrected mask
    return [s in ('model', 'stop') for s in seg]


unsloth_image = (modal.Image.debian_slim(python_version='3.12').apt_install('git').pip_install('unsloth')
                 .env({'HF_HOME': '/vol/hf', 'TOKENIZERS_PARALLELISM': 'false'}))


@app.function(image=unsloth_image, gpu='T4', timeout=20 * 60, memory=16384, **_FN)
def audit_unsloth(rows: list, base_model: str) -> dict:
    """Unsloth's response-only masking needs the full package, which imports only with a GPU present."""
    import unsloth  # noqa: F401  (must be imported first)
    import importlib.metadata as md
    from datasets import Dataset
    from transformers import AutoTokenizer
    from unsloth.chat_templates import train_on_responses_only

    tok = AutoTokenizer.from_pretrained(base_model, token=os.environ['HF_TOKEN'])
    enc = []
    for row in rows:
        ids = tok.apply_chat_template(row['messages'], tools=row['tools'], tokenize=True)
        ids = list(ids['input_ids'] if hasattr(ids, 'input_ids') else ids)
        enc.append((ids, _segments(tok, ids)))

    class _T:
        pass
    tr = _T(); tr.tokenizer = tok; tr.data_collator = None; tr.eval_dataset = None
    tr.train_dataset = Dataset.from_list([{'input_ids': ids, 'attention_mask': [1] * len(ids)} for ids, _ in enc])
    tr = train_on_responses_only(tr, instruction_part='<|turn>user\n', response_part='<|turn>model\n', tokenizer=tok)
    n = {'stop': 0, 'stop_sup': 0, 'result': 0, 'result_sup': 0, 'model': 0, 'model_sup': 0, 'other': 0, 'other_sup': 0}
    for (ids, seg), ex in zip(enc, tr.train_dataset):
        for l, sg in zip(ex['labels'], seg):
            n[sg] += 1; n[sg + '_sup'] += l != -100
    return {'counts': n, 'versions': {p: md.version(p) for p in ('unsloth', 'unsloth_zoo', 'transformers')}}


@app.function(timeout=20 * 60, memory=16384, **_FN)
def audit_remote(rows: list, base_model: str) -> dict:
    import importlib.metadata as md
    from transformers import AutoTokenizer, GenerationConfig

    tok = AutoTokenizer.from_pretrained(base_model, token=os.environ['HF_TOKEN'])
    gen = GenerationConfig.from_pretrained(base_model, token=os.environ['HF_TOKEN'])
    eos = gen.eos_token_id if isinstance(gen.eos_token_id, list) else [gen.eos_token_id]
    out = {'base_model': base_model, 'eos_token_id': eos, 'eos_tokens': tok.convert_ids_to_tokens(eos),
           'versions': {p: md.version(p) for p in ('transformers', 'trl')}, 'recipes': {}, 'notes': {}}
    tmpl = tok.chat_template or ''
    out['notes']['template_has_generation_tag'] = '{% generation' in tmpl or '{%- generation' in tmpl

    def tally(name, masks_and_segs):
        n = {'stop': 0, 'stop_sup': 0, 'result': 0, 'result_sup': 0, 'model': 0, 'model_sup': 0, 'other': 0, 'other_sup': 0}
        for mask, seg in masks_and_segs:
            for m, s in zip(mask, seg):
                n[s] += 1; n[s + '_sup'] += bool(m)
        out['recipes'][name] = n

    enc = []
    for row in rows:
        ids = tok.apply_chat_template(row['messages'], tools=row['tools'], tokenize=True)
        if hasattr(ids, 'input_ids'):
            ids = ids['input_ids']
        enc.append((row, list(ids), _segments(tok, list(ids))))
    out['notes']['rendered_tool_turn'] = tok.decode(enc[0][1])[-600:]

    tally('model turns only (hand-written, round 1)', [(_mask_turns_only(seg), seg) for _, _, seg in enc])
    tally('model turns + stop token (hand-written, fixed)', [(_mask_fixed(seg), seg) for _, _, seg in enc])
    tally('no mask (loss on every token)', [([True] * len(seg), seg) for _, _, seg in enc])

    # transformers / TRL: assistant_only_loss uses apply_chat_template(return_assistant_tokens_mask=True)
    try:
        res = []
        for row, ids, seg in enc:
            e = tok.apply_chat_template(row['messages'], tools=row['tools'], tokenize=True, return_dict=True, return_assistant_tokens_mask=True)
            am = e.get('assistant_masks')
            am = list(am[0]) if am is not None and len(am) and isinstance(am[0], (list, tuple)) else list(am)
            assert len(am) == len(seg), (len(am), len(seg))
            res.append(([bool(x) for x in am], seg))
        tally('transformers return_assistant_tokens_mask (TRL assistant_only_loss)', res)
    except Exception as e:
        out['notes']['assistant_tokens_mask_error'] = repr(e)[:400]

    # Message-boundary recipe: supervise the token span each assistant message adds to the rendered prefix
    try:
        res = []
        for row, ids, seg in enc[:4]:
            mask = [False] * len(ids)
            prev = None
            for k in range(1, len(row['messages']) + 1):
                cur = tok.apply_chat_template(row['messages'][:k], tools=row['tools'], tokenize=True)
                cur = list(cur['input_ids'] if hasattr(cur, 'input_ids') else cur)
                if row['messages'][k - 1]['role'] == 'assistant' and prev is not None:
                    j = 0
                    while j < min(len(prev), len(cur)) and prev[j] == cur[j]:
                        j += 1
                    for q in range(j, min(len(cur), len(ids))):
                        if cur[q] == ids[q]:
                            mask[q] = True
                prev = cur
            res.append((mask, seg))
        tally('assistant-message span by prefix diff (first 4 trajectories)', res)
    except Exception as e:
        out['notes']['prefix_diff_error'] = repr(e)[:400]
    return out


def _probe_impl(rows: list, base_model: str, adapters: list) -> dict:
    import statistics
    import torch
    from peft import PeftModel
    from transformers import AutoModelForCausalLM, AutoTokenizer

    tok = AutoTokenizer.from_pretrained(base_model, token=os.environ['HF_TOKEN'])
    stop_id, call_id = tok.convert_tokens_to_ids(STOP), tok.convert_tokens_to_ids(CALL_OPEN)
    enc = []
    for row in rows:
        ids = tok.apply_chat_template(row['messages'], tools=row['tools'], tokenize=True)
        ids = list(ids['input_ids'] if hasattr(ids, 'input_ids') else ids)
        if len(ids) > 32768:
            continue
        seg = _segments(tok, ids)
        pos = [i - 1 for i, s in enumerate(seg) if s == 'stop']  # hidden state at i-1 predicts the stop at i
        enc.append((row['task_id'], ids, pos))
    print(f'{len(enc)} trajectories, {sum(len(p) for _, _, p in enc)} stop positions', flush=True)
    base = AutoModelForCausalLM.from_pretrained(base_model, dtype=torch.bfloat16, device_map='cuda', token=os.environ['HF_TOKEN'])
    base.eval()
    out = {'base_model': base_model, 'trajectories': len(enc), 'stop_positions': sum(len(p) for _, _, p in enc), 'models': {}}

    def run(model, name):
        p_stop, p_call, top1 = [], [], 0
        with torch.no_grad():
            for _, ids, pos in enc:
                x = torch.tensor([ids], device='cuda')
                logits = model(input_ids=x, logits_to_keep=pos).logits[0].float()
                pr = torch.softmax(logits, -1)
                p_stop += pr[:, stop_id].tolist(); p_call += pr[:, call_id].tolist()
                top1 += int((pr.argmax(-1) == stop_id).sum())
        n = len(p_stop)
        out['models'][name] = {'n': n, 'mean_p_stop': sum(p_stop) / n, 'median_p_stop': statistics.median(p_stop), 'min_p_stop': min(p_stop),
                               'mean_p_call': sum(p_call) / n, 'max_p_call': max(p_call), 'stop_is_argmax': top1,
                               'frac_p_stop_below_0.5': sum(p < 0.5 for p in p_stop) / n,
                               'p_stop_deciles': [round(sorted(p_stop)[min(n - 1, int(q * n / 10))], 4) for q in range(11)]}
        print(name, json.dumps(out['models'][name]), flush=True)

    run(base, 'base')
    for a in adapters:
        m = PeftModel.from_pretrained(base, f'/vol/adapters/{a}')
        m.eval(); run(m, a)
        base = m.unload()
    return out


@app.function(gpu='H200', memory=131072, timeout=2 * 60 * 60, **_FN)
def probe_h200(rows: list, base_model: str, adapters: list) -> dict:
    return _probe_impl(rows, base_model, adapters)


@app.function(gpu='H100', memory=65536, timeout=60 * 60, **_FN)
def probe_h100(rows: list, base_model: str, adapters: list) -> dict:
    return _probe_impl(rows, base_model, adapters)


def _rows(path: str) -> list:
    return [{k: r[k] for k in ('task_id', 'messages', 'tools')} for r in map(json.loads, Path(path).read_text().splitlines()) if r]


@app.local_entrypoint()
def audit(data: str, base_model: str = 'google/gemma-4-31b-it', out: str = 'artifacts/paper/stop_audit.json'):
    res = audit_remote.remote(_rows(data), base_model)
    try:
        u = audit_unsloth.remote(_rows(data), base_model)
        res['recipes']['unsloth train_on_responses_only(<|turn>user / <|turn>model)'] = u['counts']
        res['versions'].update(u['versions']); res['notes'].pop('unsloth_error', None)
    except Exception as e:
        res['notes']['unsloth_error'] = repr(e)[:600]
    Path(out).parent.mkdir(parents=True, exist_ok=True); Path(out).write_text(json.dumps(res, indent=1))
    print(json.dumps(res, indent=1))


@app.local_entrypoint()
def probe(data: str, adapters: str, base_model: str = 'google/gemma-4-31b-it', gpu: str = 'H200', out: str = ''):
    fn = probe_h200 if gpu == 'H200' else probe_h100
    res = fn.remote(_rows(data), base_model, [a for a in adapters.split(',') if a])
    out = out or f"artifacts/paper/stop_probe_{base_model.split('/')[-1]}.json"
    Path(out).parent.mkdir(parents=True, exist_ok=True); Path(out).write_text(json.dumps(res, indent=1))
    print(json.dumps(res, indent=1))
